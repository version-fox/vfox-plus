// Generates the icon font and the `AppIcons` class from `shared/icons.json`.
//
//   cd flutter && dart run tool/generate_icon_font.dart
//
// The Material Symbols Rounded variable font is about 15 MB. Only the glyphs
// listed in `shared/icons.json` are kept, with every variable axis (fill,
// weight, grade and optical size), using the `font-subset` tool that ships
// with Flutter. The source font comes from the `material_symbols_icons`
// development dependency, whose fonts have corrected vertical metrics.
//
// Outputs:
//   assets/fonts/MaterialSymbolsRounded.ttf   a build output, not committed
//   lib/src/ui/icons/app_icons.g.dart         committed
//
// The output only depends on the inputs, so CI and the sandbox generate the
// font before every build.

import 'dart:convert';
import 'dart:io';
import 'dart:isolate';

import 'package:material_symbols_icons/iconname_to_unicode_map.dart';

const String _manifestPath = '../shared/icons.json';
const String _fontOutput = 'assets/fonts/MaterialSymbolsRounded.ttf';
const String _dartOutput = 'lib/src/ui/icons/app_icons.g.dart';
const String _fontFamily = 'MaterialSymbolsRounded';

Future<void> main(List<String> arguments) async {
  if (!File('pubspec.yaml').existsSync() || !File(_manifestPath).existsSync()) {
    _fail('Run this tool from the flutter/ directory of the repository.');
  }

  final manifest = jsonDecode(File(_manifestPath).readAsStringSync()) as Map<String, Object?>;
  final icons = (manifest['icons']! as Map<String, Object?>).cast<String, String>();
  final codePoints = <String, int>{};
  for (final MapEntry<String, String> icon in icons.entries) {
    final int? codePoint = materialSymbolsIconNameToUnicodeMap[icon.value];
    if (codePoint == null) {
      _fail('Unknown Material Symbol "${icon.value}" for "${icon.key}".');
    }
    codePoints[icon.key] = codePoint;
  }

  final Uri? fontUri = await Isolate.resolvePackageUri(
    Uri.parse('package:material_symbols_icons/fonts/MaterialSymbolsRounded.ttf'),
  );
  if (fontUri == null || !File.fromUri(fontUri).existsSync()) {
    _fail('Cannot find the material_symbols_icons font. Run `flutter pub get` first.');
  }

  final String fontSubset = _findFontSubset();
  File(_fontOutput).parent.createSync(recursive: true);
  final Process process = await Process.start(fontSubset, <String>[_fontOutput, File.fromUri(fontUri).path]);
  final Set<int> uniqueCodePoints = codePoints.values.toSet();
  process.stdin.writeln(uniqueCodePoints.join(' '));
  await process.stdin.close();
  final List<String> output = await Future.wait(<Future<String>>[
    process.stdout.transform(utf8.decoder).join(),
    process.stderr.transform(utf8.decoder).join(),
  ]);
  if (await process.exitCode != 0) {
    _fail('font-subset failed:\n${output.join('\n')}');
  }

  File(_dartOutput)
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(_generateDart(icons, codePoints));
  await Process.run(Platform.resolvedExecutable, <String>['format', _dartOutput]);

  stdout.writeln(
    'Wrote ${icons.length} icons (${uniqueCodePoints.length} glyphs, '
    '${File(_fontOutput).lengthSync()} bytes) to $_fontOutput and $_dartOutput.',
  );
}

String _generateDart(Map<String, String> icons, Map<String, int> codePoints) {
  final List<String> names = icons.keys.toList()..sort();
  final buffer = StringBuffer()
    ..writeln(File('tool/license_header.txt').readAsStringSync().trimRight())
    ..writeln()
    ..writeln('// GENERATED by tool/generate_icon_font.dart from shared/icons.json. Do not edit.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// The Material Symbols Rounded icons used by the application.')
    ..writeln('///')
    ..writeln('/// The glyphs come from a subset of the variable font, so [Icon.fill],')
    ..writeln('/// [Icon.weight], [Icon.grade] and [Icon.opticalSize] all take effect.')
    ..writeln('abstract final class AppIcons {')
    ..writeln('  /// The font family of every icon.')
    ..writeln("  static const String fontFamily = '$_fontFamily';");
  for (final name in names) {
    final String hex = codePoints[name]!.toRadixString(16);
    buffer
      ..writeln()
      ..writeln('  /// Material Symbol `${icons[name]}`.')
      ..writeln('  static const IconData $name = IconData(0x$hex, fontFamily: fontFamily);');
  }
  buffer
    ..writeln()
    ..writeln('  /// Every icon by name, in alphabetical order.')
    ..writeln('  static const Map<String, IconData> all = <String, IconData>{');
  for (final name in names) {
    buffer.writeln("    '$name': $name,");
  }
  buffer
    ..writeln('  };')
    ..writeln('}');
  return buffer.toString();
}

/// Locates the `font-subset` executable in the Flutter SDK cache.
String _findFontSubset() {
  final String flutterRoot =
      Platform.environment['FLUTTER_ROOT'] ??
      // dart is at <flutter>/bin/cache/dart-sdk/bin/dart.
      File(Platform.resolvedExecutable).parent.parent.parent.parent.parent.path;
  final engine = Directory('$flutterRoot/bin/cache/artifacts/engine');
  final String executable = Platform.isWindows ? 'font-subset.exe' : 'font-subset';
  final String prefix = switch (Platform.operatingSystem) {
    'linux' => 'linux-',
    'macos' => 'darwin-',
    'windows' => 'windows-',
    final String os => _fail('Unsupported operating system: $os'),
  };
  if (engine.existsSync()) {
    for (final Directory directory in engine.listSync().whereType<Directory>()) {
      final file = File('${directory.path}/$executable');
      if (directory.path.split(Platform.pathSeparator).last.startsWith(prefix) && file.existsSync()) {
        return file.path;
      }
    }
  }
  _fail('Cannot find font-subset under ${engine.path}. Run `flutter precache` or set FLUTTER_ROOT.');
}

Never _fail(String message) {
  stderr.writeln(message);
  exit(1);
}
