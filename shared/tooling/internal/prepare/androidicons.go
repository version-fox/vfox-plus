// pathPattern is the one shape that the icons of the package have: a path in the
// colour of the text.
var pathPattern = regexp.MustCompile(`<path fill="currentColor" d="([^"]*)"/>`)

// vectorDrawable is an icon as a vector drawable, which takes the colour of the
// theme (colorControlNormal) unless a view tints it.
func (s iconSet) vectorDrawable(icon iconBody, symbol, style string, mirrored bool, source iconSource) (string, error) {
	if icon.Left != 0 || icon.Top != 0 {
		return "", errors.New("starts somewhere else than 0,0")
	}
	width, height := s.Width, s.Height
	if icon.Width != nil {
		width = *icon.Width
	}
	if icon.Height != nil {
		height = *icon.Height
	}
	paths := pathPattern.FindAllStringSubmatch(icon.Body, -1)
	if len(paths) == 0 || strings.TrimSpace(pathPattern.ReplaceAllString(icon.Body, "")) != "" {
		return "", errors.New(`is not made of paths like <path fill="currentColor" d="…"/>`)
	}
	number := func(value float64) string { return strconv.FormatFloat(value, 'f', -1, 64) }
	var out strings.Builder
	out.WriteString(androidHeader)
	fmt.Fprintf(&out, "<!-- %s from shared/icons.json: do not edit. Material Symbols Rounded %q (%s), %s %s. -->\n",
		androidMarker, symbol, style, source.Package, source.Version)
	out.WriteString("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n")
	fmt.Fprintf(&out, "    android:width=\"%sdp\"\n    android:height=\"%sdp\"\n", number(width), number(height))
	fmt.Fprintf(&out, "    android:viewportWidth=\"%s\"\n    android:viewportHeight=\"%s\"\n", number(width), number(height))
	if mirrored {
		out.WriteString("    android:autoMirrored=\"true\"\n")
	}
	out.WriteString("    android:tint=\"?attr/colorControlNormal\">\n")
	for _, p := range paths {
		out.WriteString("    <path\n        android:fillColor=\"@android:color/white\"\n")
		fmt.Fprintf(&out, "        android:pathData=\"%s\" />\n", p[1])
	}
	out.WriteString("</vector>\n")
	return out.String(), nil
}

// androidFiles are the drawables of the section by file name, and the problems of
// the icons that the package cannot give, one line each.
func androidFiles(set iconSet, manifest iconManifest) (map[string]string, []string) {
	files := map[string]string{}
	var problems []string
	names := make([]string, 0, len(manifest.Android.Icons))
	for name := range manifest.Android.Icons {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		symbol := manifest.Android.Icons[name]
		outlined, filled := iconNames(symbol)
		variants := []struct{ file, packageName, style string }{{"ic_" + androidName(name) + ".xml", outlined, "outlined"}}
		if slices.Contains(manifest.Android.Filled, name) {
			variants = append(variants, struct{ file, packageName, style string }{"ic_" + androidName(name) + "_fill.xml", filled, "filled"})
		}
		for _, variant := range variants {
			icon, err := set.find(variant.packageName)
			if err != nil {
				problems = append(problems, name+": "+err.Error())
				continue
			}
			vector, err := set.vectorDrawable(icon, symbol, variant.style, slices.Contains(manifest.Android.Mirrored, name), manifest.Source)
			if err != nil {
				problems = append(problems, name+": "+variant.packageName+" "+err.Error())
				continue
			}
			files[variant.file] = vector
		}
	}
	return files, problems
}

// writeAndroidIcons writes the drawables of the section into dir, removes the ones
// that an earlier run wrote and the section no longer names, leaves every other file
// alone, and returns the names of the files that it wrote.
func writeAndroidIcons(set iconSet, manifest iconManifest, dir string) ([]string, error) {
	files, problems := androidFiles(set, manifest)
	if len(problems) > 0 {
		return nil, fmt.Errorf("icons of \"android\" in shared/icons.json that the package cannot give:\n  %s", strings.Join(problems, "\n  "))
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	written := make([]string, 0, len(files))
	for name, content := range files {
		target := filepath.Join(dir, name)
		if err := os.WriteFile(target, []byte(content), 0o666); err != nil {
			return nil, fmt.Errorf("write %s: %w", target, err)
		}
		written = append(written, name)
	}
	sort.Strings(written)
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		name := entry.Name()
		if _, kept := files[name]; kept || entry.IsDir() || !strings.HasPrefix(name, "ic_") || !strings.HasSuffix(name, ".xml") {
			continue
		}
		content, err := os.ReadFile(filepath.Join(dir, name)) //nolint:gosec // A file of the repository.
		if err != nil {
			return nil, err
		}
		if strings.Contains(string(content), androidMarker) {
			if err := os.Remove(filepath.Join(dir, name)); err != nil {
				return nil, err
			}
		}
	}
	return written, nil
}

// RunAndroidIcons writes the vector drawables of the icons of the Android app.
func RunAndroidIcons(args []string) error {
	fs := flag.NewFlagSet("vfxtool android-icons", flag.ContinueOnError)
	rootFlag := fs.String("root", "", "root of the repository (default: located from the current directory)")
	fs.Usage = func() { _, _ = fmt.Fprintln(fs.Output(), androidUsage) }
	if err := fs.Parse(args); err != nil {
		return err
	}
	if len(fs.Args()) != 0 {
		return errors.New("android-icons takes no arguments; " + androidUsage)
	}
	root, err := resolveRepositoryRoot(*rootFlag)
	if err != nil {
		return err
	}
	manifest, err := readManifest(filepath.Join(root, "shared", "icons.json"))
	if err != nil {
		return err
	}
	if len(manifest.Android.Icons) == 0 {
		return errors.New(`shared/icons.json has no "android" icons`)
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	defer stop()
	tarball, err := fetchTarball(ctx, manifest.Source, os.Stdout)
	if err != nil {
		return err
	}
	set, err := readIconSet(tarball)
	if err != nil {
		return err
	}
	dir := filepath.Join(root, "android", "app", "src", "main", "res", "drawable")
	written, err := writeAndroidIcons(set, manifest, dir)
	if err != nil {
		return err
	}
	fmt.Printf("Wrote %d vector drawables into %s\n", len(written), dir)
	return nil
}

// resolveRepositoryRoot is the --root flag, or the directory above the one that has
// shared/icons.json, from the current directory up.
func resolveRepositoryRoot(flagRoot string) (string, error) {
	hasManifest := func(dir string) bool {
		_, err := os.Stat(filepath.Join(dir, "shared", "icons.json"))
		return err == nil
	}
	if flagRoot != "" {
		abs, err := filepath.Abs(flagRoot)
		if err != nil {
			return "", fmt.Errorf("resolve --root %s: %w", flagRoot, err)
		}
		if !hasManifest(abs) {
			return "", fmt.Errorf("--root %s has no shared/icons.json", abs)
		}
		return abs, nil
	}
	cwd, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("get working directory: %w", err)
	}
	for dir := cwd; ; dir = filepath.Dir(dir) {
		if hasManifest(dir) {
			return dir, nil
		}
		if filepath.Dir(dir) == dir {
			return "", fmt.Errorf("no shared/icons.json above %s (use --root)", cwd)
		}
	}
}
