// The Android app draws the same Material Symbols Rounded as the other interfaces,
// as vector drawables: `vfxtool android-icons` cuts the symbols that the "android"
// section of shared/icons.json lists out of the npm package that the manifest pins,
// and writes them into android/app/src/main/res/drawable. Unlike the SVGs of the
// desktop interface, which are not committed, these are committed: the Gradle build
// of the app needs nothing but Gradle.

// androidUsage is the command line of android-icons.
const androidUsage = "Usage: android-icons [--root DIR]"

// androidIcons is the "android" section of shared/icons.json.
type androidIcons struct {
	// Icons are the symbols by name.
	Icons map[string]string `json:"icons"`
	// Filled are the names that get a filled drawable, ic_NAME_fill.xml, next to the
	// outlined one.
	Filled []string `json:"filled"`
	// Mirrored are the names whose drawables turn around in a right-to-left language.
	Mirrored []string `json:"mirrored"`
}

var (
	androidNamePattern   = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)
	androidSymbolPattern = regexp.MustCompile(`^[a-z0-9]+(_[a-z0-9]+)*$`)
)

// validate checks the section against the icons of the other interfaces, which
// mean the same symbol when they have the same name.
func (a androidIcons) validate(shared map[string]string) error {
	var problems []string
	for name, symbol := range a.Icons {
		if !androidNamePattern.MatchString(name) {
			problems = append(problems, fmt.Sprintf("%q is not a name in camel case", name))
		}
		if !androidSymbolPattern.MatchString(symbol) {
			problems = append(problems, fmt.Sprintf("%s: %q is not a symbol of Material Symbols (lower case, with underscores)", name, symbol))
		}
		if other, ok := shared[name]; ok && other != symbol {
			problems = append(problems, fmt.Sprintf("%s is %q here and %q in \"icons\"", name, symbol, other))
		}
	}
	for field, names := range map[string][]string{"filled": a.Filled, "mirrored": a.Mirrored} {
		for _, name := range names {
			if _, ok := a.Icons[name]; !ok {
				problems = append(problems, fmt.Sprintf("%q of %q is not one of the icons", name, field))
			}
		}
	}
	if len(problems) == 0 {
		return nil
	}
	sort.Strings(problems)
	return errors.New(strings.Join(problems, "; "))
}

// androidName is the resource name of a name of the manifest: scanQr is scan_qr.
func androidName(name string) string {
	var out strings.Builder
	for i, r := range name {
		if unicode.IsUpper(r) && i > 0 {
			out.WriteByte('_')
		}
		out.WriteRune(unicode.ToLower(r))
	}
	return out.String()
}

// androidMarker is in the comment of every file that android-icons writes, which is
// how it tells them from the hand-made drawables next to them.
const androidMarker = "Generated by `vfxtool android-icons`"

