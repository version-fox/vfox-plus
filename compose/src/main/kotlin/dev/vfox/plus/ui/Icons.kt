/**
 * The Material Symbols Rounded icons of shared/icons.json, cut out of the font
 * at build time (build.gradle.kts): one font with every icon outlined and one
 * with every icon filled, for the selected destination.
 */
object AppIcons {
    private fun resource(path: String): ByteArray =
        AppIcons::class.java.getResourceAsStream(path)?.use { it.readBytes() }
            ?: error("$path is missing from the resources; it is generated by the build")

    /** The outlined icons. */
    val outlined = FontFamily(Font("MaterialSymbolsRounded", resource("/fonts/MaterialSymbolsRounded.ttf")))

    /** The filled icons. */
    val filled = FontFamily(Font("MaterialSymbolsRounded-Filled", resource("/fonts/MaterialSymbolsRounded-Filled.ttf")))

    /** The code point of every icon, by its meaning, such as `sdks`. */
    val codepoints: Map<String, Int> =
        Json
            .parseToJsonElement(resource("/fonts/icons.json").decodeToString())
            .jsonObject
            .getValue("icons")
            .jsonObject
            .mapValues {
                it.value.jsonObject
                    .getValue("codepoint")
                    .jsonPrimitive.int
            }

    /** The text that draws the icon of [meaning]. */
    fun glyph(meaning: String): String = String(Character.toChars(codepoints[meaning] ?: error("Unknown icon $meaning")))
}

/**
 * The icon of [meaning] (a name of shared/icons.json), outlined or [filled].
 * Switching between them cross-fades on the fast effects spring. Icons are
 * decorative: the elements around them carry the text for assistive
 * technologies.
 */
@Composable
fun Icon(
    meaning: String,
    modifier: Modifier = Modifier,
    filled: Boolean = false,
    size: Dp = 24.dp,
    tint: Color = LocalContentColor.current,
) {
    val fontSize = with(LocalDensity.current) { size.toSp() }
    Box(modifier.size(size).clearAndSetSemantics {}, contentAlignment = Alignment.Center) {
        Crossfade(filled, animationSpec = MaterialTheme.motionScheme.fastEffectsSpec()) { isFilled ->
            Text(
                AppIcons.glyph(meaning),
                color = tint,
                style =
                    TextStyle(
                        fontFamily = if (isFilled) AppIcons.filled else AppIcons.outlined,
                        fontSize = fontSize,
                        lineHeight = fontSize,
                        textAlign = TextAlign.Center,
                    ),
            )
        }
    }
}
