/** The configuration keys of vfox that get an editor of their own. */
object ConfigKeys {
    const val PROXY_ENABLE = "proxy.enable"
    const val PROXY_URL = "proxy.url"
    const val REGISTRY = "registry.address"
    const val STORAGE = "storage.sdkPath"
    const val LEGACY_ENABLE = "legacyVersionFile.enable"
    const val LEGACY_STRATEGY = "legacyVersionFile.strategy"
    const val CACHE = "cache.availableHookDuration"
    const val HTTP_TIMEOUT = "plugin.http.timeout"
    const val DOWNLOAD_TIMEOUT = "plugin.http.downloadTimeout"
    const val GITIGNORE = "gitignore.enable"
    val all =
        setOf(PROXY_ENABLE, PROXY_URL, REGISTRY, STORAGE, LEGACY_ENABLE, LEGACY_STRATEGY, CACHE, HTTP_TIMEOUT, DOWNLOAD_TIMEOUT, GITIGNORE)
}

/** The licenses of the bundled libraries and of the icon font, generated by the build. */
fun licenseText(): String =
    listOf("/licenses/THIRD-PARTY-NOTICES.txt", "/fonts/MaterialSymbolsRounded-LICENSE.txt")
        .mapNotNull { path -> object {}.javaClass.getResourceAsStream(path)?.use { it.readBytes().decodeToString() } }
        .joinToString("\n\n" + "-".repeat(72) + "\n\n") { it.trim() }

/** A row of a settings group: an icon, a title with an optional supporting text, and a control. */
@Composable
private fun SettingRow(
    index: Int,
    count: Int,
    title: String,
    icon: String? = null,
    supporting: String? = null,
    onClick: (() -> Unit)? = null,
    below: (@Composable () -> Unit)? = null,
    trailing: @Composable RowScope.() -> Unit = {},
) {
    SegmentedRow(index, count, onClick = onClick) {
        Column(Modifier.weight(1f)) {
            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(Gaps.l)) {
                if (icon != null) Icon(icon, tint = MaterialTheme.colorScheme.onSurfaceVariant) else Box(Modifier.width(24.dp))
                Column(Modifier.weight(1f).padding(vertical = Gaps.xs)) {
                    Text(title, style = MaterialTheme.typography.bodyLarge)
                    if (supporting != null) {
                        Text(supporting, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(Gaps.xs),
                    content = trailing,
                )
            }
            if (below != null) Box(Modifier.padding(start = 40.dp, top = Gaps.s, bottom = Gaps.xs)) { below() }
        }
    }
}

/** Settings of the application and of vfox. */
@Composable
fun SettingsPage() {
    val model = app.model
    LaunchedEffect(model.vfox.availability) {
        if (model.vfox.availability == VfoxAvailability.READY) model.vfoxConfig.entries.load()
    }
    Pane {
        Column(Modifier.verticalScroll(rememberScrollState())) {
            PageHeader(t("navSettings"))
            Column(
                Modifier
                    .align(
                        Alignment.CenterHorizontally,
                    ).widthIn(max = 840.dp)
                    .padding(start = Gaps.xl, end = Gaps.xl, bottom = Gaps.xxl),
            ) {
                Appearance()
                VfoxSection()
                Configuration()
                About()
            }
        }
    }
}

@Composable
private fun Appearance() {
    val context = app
    val model = context.model
    val settings = model.settings.settings
    GroupHeader(t("settingsAppearance"))
    Column(verticalArrangement = Arrangement.spacedBy(Gaps.hairline)) {
        SettingRow(0, 4, t("settingsTheme"), "darkMode") {
            ChoiceGroup(
                listOf(
                    Choice(ThemePreference.SYSTEM, t("themeSystem"), "systemMode"),
                    Choice(ThemePreference.LIGHT, t("themeLight"), "lightMode"),
                    Choice(ThemePreference.DARK, t("themeDark"), "darkMode"),
                ),
                settings.theme,
            ) { theme -> model.updateSettings { it.copy(theme = theme) } }
        }
        SettingRow(
            1,
            4,
            t("settingsSystemColor"),
            "palette",
            onClick = { model.updateSettings { it.copy(useSystemColor = !it.useSystemColor) } },
        ) {
            val label = t("settingsSystemColor")
            Switch(
                checked = settings.useSystemColor,
                onCheckedChange = { checked -> model.updateSettings { it.copy(useSystemColor = checked) } },
                modifier = Modifier.semantics { contentDescription = label },
            )
        }
        SettingRow(2, 4, t("settingsColor"), below = {
            FlowRow(horizontalArrangement = Arrangement.spacedBy(Gaps.s)) {
                val dark = MaterialTheme.colorScheme.surface.luminance() < 0.5f
                SEED_COLORS.forEachIndexed { index, seed ->
                    Swatch(seed, index, selected = !settings.useSystemColor && settings.seedColor == seed, dark = dark) {
                        model.updateSettings { it.copy(seedColor = seed, useSystemColor = false) }
                    }
                }
            }
        })
        SettingRow(3, 4, t("settingsLanguage"), "language") {
            ChoiceGroup(
                listOf(
                    Choice(LanguagePreference.SYSTEM, t("languageSystem")),
                    // Language names are always shown in their own language.
                    Choice(LanguagePreference.ENGLISH, "English"),
                    Choice(LanguagePreference.SIMPLIFIED_CHINESE, "简体中文"),
                ),
                settings.language,
            ) { language -> model.updateSettings { it.copy(language = language) } }
        }
    }
}

/** The relative luminance of a colour, to pick a readable check mark. */
private fun Color.luminance(): Float = 0.2126f * red + 0.7152f * green + 0.0722f * blue

/** A seed colour: a circle that morphs into a flower and turns when it is selected. */
@Composable
private fun Swatch(
    seed: Long,
    index: Int,
    selected: Boolean,
    dark: Boolean,
    onClick: () -> Unit,
) {
    val morph = remember { Morph(MaterialShapes.Circle, MaterialShapes.Flower) }
    val progress by animateFloatAsState(if (selected) 1f else 0f, MaterialTheme.motionScheme.fastSpatialSpec())
    val primary = remember(seed, dark) { colorSchemeFor(seed, dark).primary }
    val label = t("settingsColorOption", "index" to index + 1)
    Box(
        Modifier
            .size(40.dp)
            .semantics(mergeDescendants = true) {
                contentDescription = label
                this.selected = selected
            }.clickable(role = Role.RadioButton, onClick = onClick),
        contentAlignment = Alignment.Center,
    ) {
        Box(Modifier.size(40.dp).graphicsLayer { rotationZ = 34f * progress }.background(primary, MorphShape(morph, progress)))
        Icon("check", size = 20.dp, tint = (if (dark) Color.Black else Color.White).copy(alpha = progress.coerceIn(0f, 1f)))
    }
}

@Composable
private fun VfoxSection() {
    val context = app
    val model = context.model
    val vfox = model.vfox
    val settings = model.settings.settings
    var environment by remember(settings.extraEnvironment) { mutableStateOf(formatEnvironmentLines(settings.extraEnvironment)) }
    var environmentError by remember { mutableStateOf<String?>(null) }
    val saved = t("settingsSaved")
    val source =
        when {
            vfox.executable == null -> t("settingsExecutableMissing")
            vfox.isCustomExecutable -> t("settingsExecutableCustom")
            else -> t("settingsExecutableDetected")
        }
    val details =
        listOfNotNull(
            vfox.executable ?: "vfox",
            source,
            vfox.version?.let {
                t("settingsVfoxVersion", "version" to it)
            },
        ).joinToString(" · ")
    val invalidMessage: (List<Int>) -> String = { lines ->
        context.localizations.t(
            "settingsEnvironmentInvalid",
            "count" to lines.size,
            "lines" to lines.joinToString(", "),
        )
    }
    GroupHeader(t("settingsVfox"))
    Column(verticalArrangement = Arrangement.spacedBy(Gaps.hairline)) {
        SettingRow(0, 2, t("settingsExecutable"), "terminal", supporting = details) {
            if (vfox.availability == VfoxAvailability.CHECKING) {
                val label = t("vfoxCheckingTitle")
                LoadingIndicator(Modifier.size(36.dp).semantics { contentDescription = label })
            } else if (vfox.isCustomExecutable) {
                TooltipIconButton("refresh", t("settingsExecutableDetect")) { model.updateSettings { it.copy(vfoxExecutable = null) } }
            }
            FilledTonalButton(onClick = { context.locateVfox() }) { Text(t("actionBrowse")) }
        }
        SettingRow(1, 2, t("settingsEnvironment"), "environment", supporting = t("settingsEnvironmentHelp"), below = {
            Column(Modifier.fillMaxWidth(), horizontalAlignment = Alignment.End, verticalArrangement = Arrangement.spacedBy(Gaps.s)) {
                val label = t("settingsEnvironment")
                OutlinedTextField(
                    value = environment,
                    onValueChange = {
                        environment = it
                        environmentError = null
                    },
                    placeholder = { Text("VFOX_NODEJS_MIRROR=https://npmmirror.com/mirrors/node", fontFamily = FontFamily.Monospace) },
                    textStyle = MaterialTheme.typography.bodyMedium.copy(fontFamily = FontFamily.Monospace),
                    isError = environmentError != null,
                    supportingText = environmentError?.let { { Text(it) } },
                    minLines = 3,
                    modifier = Modifier.fillMaxWidth().semantics { contentDescription = label },
                )
                Button(onClick = {
                    val parsed = parseEnvironmentLines(environment)
                    if (parsed.invalidLines.isNotEmpty()) {
                        environmentError = invalidMessage(parsed.invalidLines)
                    } else {
                        model.updateSettings { it.copy(extraEnvironment = parsed.variables) }
                        context.scope.launch { context.snackbars.showSnackbar(saved) }
                    }
                }) { Text(t("actionSave")) }
            }
        })
    }
}

@Composable
private fun Configuration() {
    val context = app
    val model = context.model
    val config = model.vfoxConfig
    val entries = config.entries
    GroupHeader(t("settingsVfoxConfig"))
    Text(
        t("settingsVfoxConfigHelp"),
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
        modifier = Modifier.padding(start = Gaps.l, end = Gaps.l, bottom = Gaps.m),
    )
    if (model.vfox.availability != VfoxAvailability.READY) return
    if (!entries.hasValue) {
        val error = entries.error
        Box(Modifier.fillMaxWidth()) {
            if (error == null) LoadingMessage() else ErrorMessage(t("settingsVfoxConfigError"), error) { entries.load() }
        }
        return
    }
    val other = entries.value.orEmpty().filter { it.key !in ConfigKeys.all }
    Column(verticalArrangement = Arrangement.spacedBy(Gaps.hairline)) {
        ConfigSwitch(0, 4, ConfigKeys.PROXY_ENABLE, t("configProxyEnable"), "proxy")
        ConfigText(1, 4, ConfigKeys.PROXY_URL, t("configProxyUrl"), null, "http://127.0.0.1:7890")
        ConfigText(2, 4, ConfigKeys.REGISTRY, t("configRegistry"), "registry", t("configRegistryHint"))
        ConfigText(3, 4, ConfigKeys.STORAGE, t("configStorage"), "storage", t("configStorageHint"), pickDirectory = true)
    }
    Box(Modifier.size(Gaps.l))
    Column(verticalArrangement = Arrangement.spacedBy(Gaps.hairline)) {
        ConfigSwitch(0, 3, ConfigKeys.LEGACY_ENABLE, t("configLegacyEnable"), "legacyFiles", t("configLegacyEnableHelp"))
        ConfigChoice(
            1,
            3,
            ConfigKeys.LEGACY_STRATEGY,
            t("configLegacyStrategy"),
            listOf(
                "specified" to t("strategySpecified"),
                "latest_installed" to t("strategyLatestInstalled"),
                "latest_available" to t("strategyLatestAvailable"),
            ),
        )
        ConfigSwitch(2, 3, ConfigKeys.GITIGNORE, t("configGitignore"), "gitignore", t("configGitignoreHelp"))
    }
    Box(Modifier.size(Gaps.l))
    Column(verticalArrangement = Arrangement.spacedBy(Gaps.hairline)) {
        ConfigText(0, 3, ConfigKeys.CACHE, t("configCache"), "cache", "12h", t("configCacheHelp"))
        ConfigText(1, 3, ConfigKeys.HTTP_TIMEOUT, t("configHttpTimeout"), "timeout", "30s", t("configTimeoutHelp"))
        ConfigText(2, 3, ConfigKeys.DOWNLOAD_TIMEOUT, t("configDownloadTimeout"), null, "30m", t("configTimeoutHelp"))
    }
    if (other.isNotEmpty()) {
        GroupHeader(t("configOther"))
        Column(verticalArrangement = Arrangement.spacedBy(Gaps.hairline)) {
            other.forEachIndexed { index, entry -> ConfigText(index, other.size, entry.key, entry.key, null, "") }
        }
    }
}

/** Saves a vfox setting and reports the result in a snack bar. */
private fun dev.vfox.plus.ui.AppContext.saveConfig(
    saved: String,
    save: suspend () -> Unit,
) {
    scope.launch {
        val message =
            try {
                save()
                saved
            } catch (error: VfoxException) {
                error.message ?: error.toString()
            }
        snackbars.showSnackbar(message)
    }
}

@Composable
private fun ConfigSwitch(
    index: Int,
    count: Int,
    key: String,
    title: String,
    icon: String,
    help: String? = null,
) {
    val context = app
    val config = context.model.vfoxConfig
    val value = config.valueFor(key) == "true"
    val saving = config.isSaving(key)
    val saved = t("settingsSaved")
    val toggle = { if (!saving) context.saveConfig(saved) { config.set(key, (!value).toString()) } }
    SettingRow(index, count, title, icon, supporting = help, onClick = toggle) {
        Switch(
            checked = value,
            onCheckedChange = { toggle() },
            enabled = !saving,
            modifier =
                Modifier.semantics {
                    contentDescription =
                        title
                },
        )
    }
}

@Composable
private fun ConfigChoice(
    index: Int,
    count: Int,
    key: String,
    title: String,
    choices: List<Pair<String, String>>,
) {
    val context = app
    val config = context.model.vfoxConfig
    val value = config.valueFor(key).orEmpty()
    var expanded by remember { mutableStateOf(false) }
    val saved = t("settingsSaved")
    SettingRow(index, count, title) {
        ExposedDropdownMenuBox(expanded = expanded, onExpandedChange = { expanded = it }) {
            OutlinedTextField(
                value = choices.firstOrNull { it.first == value }?.second ?: value,
                onValueChange = {},
                readOnly = true,
                singleLine = true,
                enabled = !config.isSaving(key),
                trailingIcon = { Icon("expandMore") },
                modifier =
                    Modifier.width(260.dp).menuAnchor(ExposedDropdownMenuAnchorType.PrimaryNotEditable).semantics {
                        contentDescription =
                            title
                    },
            )
            ExposedDropdownMenu(
                expanded = expanded,
                onDismissRequest = { expanded = false },
                shape = RoundedCornerShape(Corners.large),
                containerColor = MaterialTheme.colorScheme.surfaceContainer,
            ) {
                choices.forEach { (choice, label) ->
                    DropdownMenuItem(
                        text = { Text(label) },
                        onClick = {
                            expanded = false
                            if (choice != value) context.saveConfig(saved) { config.set(key, choice) }
                        },
                    )
                }
            }
        }
    }
}

/** Values typed into configuration fields and not saved yet, by key. */
private val drafts = mutableStateMapOf<String, String>()

@Composable
private fun ConfigText(
    index: Int,
    count: Int,
    key: String,
    title: String,
    icon: String?,
    hint: String,
    help: String? = null,
    pickDirectory: Boolean = false,
) {
    val context = app
    val config = context.model.vfoxConfig
    val stored = config.valueFor(key).orEmpty()
    val value = drafts[key] ?: stored
    val saved = t("settingsSaved")
    val save: (String) -> Unit = { text ->
        drafts.remove(key)
        val trimmed = text.trim()
        // Clearing a field resets the key; if vfox rejects a value, the reload shows the stored one again.
        if (trimmed != stored) context.saveConfig(saved) { if (trimmed.isEmpty()) config.reset(key) else config.set(key, trimmed) }
    }
    SettingRow(index, count, title, icon, supporting = help) {
        OutlinedTextField(
            value = value,
            onValueChange = { drafts[key] = it },
            placeholder = { Text(hint) },
            singleLine = true,
            enabled = !config.isSaving(key),
            keyboardOptions = KeyboardOptions(imeAction = ImeAction.Done),
            keyboardActions = KeyboardActions(onDone = { save(value) }),
            trailingIcon =
                if (pickDirectory) {
                    {
                        TooltipIconButton("folder", t("actionBrowse")) {
                            context.scope.launch { context.services.pickDirectory(value.ifEmpty { null })?.let(save) }
                        }
                    }
                } else {
                    null
                },
            modifier =
                Modifier.width(300.dp).semantics { contentDescription = title }.onFocusChanged {
                    if (!it.isFocused && drafts.containsKey(key)) save(drafts.getValue(key))
                },
        )
    }
}

